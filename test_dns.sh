#!/bin/bash
# Скрипт тестирования канала и DNS (Пункт 6)

echo "=== Этап 1: Проверка доступности шлюза ==="
ping -c 4 10.0.0.1

echo "=== Этап 2: Проверка внешнего IP-адреса ==="
echo "Ваш текущий внешний IP:"
curl -s ifconfig.me
echo ""

echo "=== Этап 3: Анализ маршрута DNS-запросов ==="
# Проверяем, куда уходит трафик до DNS Google
traceroute 8.8.8.8

echo "Тестирование завершено. Если на Этапе 2 отобразился IP-адрес VPN-сервера, а Этап 3 начинается с 10.0.0.1 — утечек нет."
